const ALL_EMOJI: Emoji[] = EMOJI_CATEGORIES.flatMap((group) => group.emoji)

const searchEmoji = (query: string) => {
  const needle = query.trim().toLowerCase()
  if (!needle) return []
  const seen = new Set<string>()
  return ALL_EMOJI.filter((entry) => {
    if (seen.has(entry.emoji) || !entry.name.includes(needle)) return false
    seen.add(entry.emoji)
    return true
  })
}

export { EMOJI_CATEGORIES, searchEmoji }
