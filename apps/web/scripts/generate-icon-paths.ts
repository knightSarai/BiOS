import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { join } from "node:path"
import { ICON_CATEGORIES } from "../src/notebook/icon-catalog.ts"

const require = createRequire(import.meta.url)
const output = join(
  import.meta.dirname,
  "../src/notebook/icon-paths.generated.ts"
)

const pathsOf = (name: string) => {
  const svg = readFileSync(
    require.resolve(`@phosphor-icons/core/assets/fill/${name}-fill.svg`),
    "utf8"
  )
  const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)].map(
    (match) => match[1]
  )
  if (paths.length === 0) throw new Error(`No paths in ${name}-fill.svg`)
  return paths
}

const entries = ICON_CATEGORIES.flatMap((group) => group.icons).map(
  (entry) => [entry.name, pathsOf(entry.name)] as const
)

writeFileSync(
  output,
  `// Generated by scripts/generate-icon-paths.ts from @phosphor-icons/core (fill weight). Run \`pnpm icons:generate\` after editing icon-catalog.ts.
const ICON_PATHS = new Map<string, readonly string[]>(${JSON.stringify(entries)})

export { ICON_PATHS }
`
)

console.log(`Wrote ${entries.length} icons to ${output}`)
