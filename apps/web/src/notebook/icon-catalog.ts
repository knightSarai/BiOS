const ALL_ICONS: CatalogIcon[] = ICON_CATEGORIES.flatMap((group) => group.icons)

const searchIcons = (query: string) => {
  const needle = query.trim().toLowerCase()
  if (!needle) return []
  return ALL_ICONS.filter((entry) =>
    `${entry.name} ${entry.keywords}`.includes(needle)
  )
}

const iconLabel = (name: string) => name.replaceAll("-", " ")

export { ICON_CATEGORIES, iconLabel, searchIcons }
export type { CatalogIcon, IconCategory }
